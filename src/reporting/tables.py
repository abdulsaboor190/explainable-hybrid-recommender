"""Table generation routines for Phase 3 experiments (E1, E2, E3, E5).

Strict constraint: Reads ONLY from results/*.csv. No models are fitted or evaluated.
Formats:
  - Markdown (.md)
  - LaTeX (.tex) with booktabs formatting
Rounding:
  - 3 decimals for RMSE and MAE
  - 4 decimals for ranking metrics (NDCG@10, P@10, R@10)
Bolding:
  - Bolds the best value per column (lowest for RMSE/MAE, highest for ranking metrics)
Saves to results/tables/.
"""

from __future__ import annotations

from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import pandas as pd

TABLES_DIR = Path("results/tables")


def _ensure_dir() -> Path:
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    return TABLES_DIR


def _format_cell(val: float, is_best: bool, decimals: int, latex: bool = False) -> str:
    """Format floating point number with specified decimals and bolding."""
    if pd.isna(val):
        return "-"
    formatted = f"{val:.{decimals}f}"
    if is_best:
        return f"\\textbf{{{formatted}}}" if latex else f"**{formatted}**"
    return formatted


def generate_e1_tables() -> List[Path]:
    """Generate Markdown and LaTeX tables for Experiment E1 (Main test comparison)."""
    _ensure_dir()
    saved: List[Path] = []

    for ds in ["movielens", "foodcom"]:
        csv_path = Path("results") / f"e1_{ds}.csv"
        df = pd.read_csv(csv_path)

        cols_metric = ["RMSE", "MAE", "NDCG@10", "P@10", "R@10", "coverage@10", "diversity@10"]
        # Find best values: min for RMSE/MAE, max for rest
        best_vals = {}
        for c in cols_metric:
            best_vals[c] = df[c].min() if c in ("RMSE", "MAE") else df[c].max()

        ds_title = "MovieLens 100K" if ds == "movielens" else "Food.com"

        # 1. Markdown
        md_lines = [
            f"# Experiment E1: Main Test Set Results ({ds_title})",
            "",
            "| Model | RMSE | MAE | NDCG@10 | P@10 | R@10 | Coverage@10 | Diversity@10 |",
            "| :--- | :---: | :---: | :---: | :---: | :---: | :---: | :---: |",
        ]
        for _, row in df.iterrows():
            m = row["model"]
            r_rmse = _format_cell(row["RMSE"], row["RMSE"] == best_vals["RMSE"], 3, latex=False)
            r_mae = _format_cell(row["MAE"], row["MAE"] == best_vals["MAE"], 3, latex=False)
            r_ndcg = _format_cell(row["NDCG@10"], row["NDCG@10"] == best_vals["NDCG@10"], 4, latex=False)
            r_p10 = _format_cell(row["P@10"], row["P@10"] == best_vals["P@10"], 4, latex=False)
            r_r10 = _format_cell(row["R@10"], row["R@10"] == best_vals["R@10"], 4, latex=False)
            r_cov = _format_cell(row["coverage@10"], row["coverage@10"] == best_vals["coverage@10"], 4, latex=False)
            r_div = _format_cell(row["diversity@10"], row["diversity@10"] == best_vals["diversity@10"], 4, latex=False)
            md_lines.append(f"| {m} | {r_rmse} | {r_mae} | {r_ndcg} | {r_p10} | {r_r10} | {r_cov} | {r_div} |")

        md_path = TABLES_DIR / f"e1_main_{ds}.md"
        md_path.write_text("\n".join(md_lines), encoding="utf-8")
        saved.append(md_path)

        # 2. LaTeX
        tex_lines = [
            "% Auto-generated by src.reporting.tables",
            "\\begin{table}[htbp]",
            "\\centering",
            f"\\caption{{Experiment E1 Main Test Results: {ds_title}}}",
            f"\\label{{tab:e1_main_{ds}}}",
            "\\begin{tabular}{lrrrrrrr}",
            "\\toprule",
            "Model & RMSE $\\downarrow$ & MAE $\\downarrow$ & NDCG@10 $\\uparrow$ & P@10 $\\uparrow$ & R@10 $\\uparrow$ & Cov@10 & Div@10 \\\\",
            "\\midrule",
        ]
        for _, row in df.iterrows():
            m = row["model"]
            r_rmse = _format_cell(row["RMSE"], row["RMSE"] == best_vals["RMSE"], 3, latex=True)
            r_mae = _format_cell(row["MAE"], row["MAE"] == best_vals["MAE"], 3, latex=True)
            r_ndcg = _format_cell(row["NDCG@10"], row["NDCG@10"] == best_vals["NDCG@10"], 4, latex=True)
            r_p10 = _format_cell(row["P@10"], row["P@10"] == best_vals["P@10"], 4, latex=True)
            r_r10 = _format_cell(row["R@10"], row["R@10"] == best_vals["R@10"], 4, latex=True)
            r_cov = _format_cell(row["coverage@10"], row["coverage@10"] == best_vals["coverage@10"], 4, latex=True)
            r_div = _format_cell(row["diversity@10"], row["diversity@10"] == best_vals["diversity@10"], 4, latex=True)
            tex_lines.append(f"{m} & {r_rmse} & {r_mae} & {r_ndcg} & {r_p10} & {r_r10} & {r_cov} & {r_div} \\\\")
        tex_lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])

        tex_path = TABLES_DIR / f"e1_main_{ds}.tex"
        tex_path.write_text("\n".join(tex_lines), encoding="utf-8")
        saved.append(tex_path)

    return saved


def generate_e2_tables() -> List[Path]:
    """Generate Markdown and LaTeX tables for Experiment E2 (Ablation with significance)."""
    _ensure_dir()
    saved: List[Path] = []

    for ds in ["movielens", "foodcom"]:
        csv_path = Path("results") / f"e2_{ds}.csv"
        sig_path = Path("results") / f"e2_significance_{ds}.csv"
        df = pd.read_csv(csv_path)
        sig_df = pd.read_csv(sig_path)

        main_df = df[df["section"] == "main_ablation"].copy()
        best_rmse = main_df["RMSE"].min()
        best_mae = main_df["MAE"].min()
        best_ndcg = main_df["NDCG@10"].max()
        best_p10 = main_df["P@10"].max()

        ds_title = "MovieLens 100K" if ds == "movielens" else "Food.com"

        # 1. Markdown
        md_lines = [
            f"# Experiment E2: Hybrid Weight Ablation & Significance ({ds_title})",
            "",
            "### Main Ablation Variants",
            "| Variant | RMSE | MAE | NDCG@10 | P@10 |",
            "| :--- | :---: | :---: | :---: | :---: |",
        ]
        for _, row in main_df.iterrows():
            v = row["description"]
            r_rmse = _format_cell(row["RMSE"], row["RMSE"] == best_rmse, 3, latex=False)
            r_mae = _format_cell(row["MAE"], row["MAE"] == best_mae, 3, latex=False)
            r_ndcg = _format_cell(row["NDCG@10"], row["NDCG@10"] == best_ndcg, 4, latex=False)
            r_p10 = _format_cell(row["P@10"], row["P@10"] == best_p10, 4, latex=False)
            md_lines.append(f"| {v} | {r_rmse} | {r_mae} | {r_ndcg} | {r_p10} |")

        md_lines.extend([
            "",
            "### Paired Significance Testing (Adaptive vs. Fixed 0.5)",
            "| Metric | Mean Difference | 95% Bootstrap CI | Wilcoxon p-value | Significant (p<0.05 & CI excludes 0) |",
            "| :--- | :---: | :---: | :---: | :---: |",
        ])
        for _, row in sig_df.iterrows():
            m = row["metric"]
            diff = f"{row['mean_difference']:.4f}"
            ci = f"[{row['ci_95_lower']:.4f}, {row['ci_95_upper']:.4f}]"
            pval = f"{row['wilcoxon_pvalue']:.2e}"
            sig = row["statistically_significant"]
            md_lines.append(f"| {m} | {diff} | {ci} | {pval} | **{sig}** |")

        md_path = TABLES_DIR / f"e2_ablation_{ds}.md"
        md_path.write_text("\n".join(md_lines), encoding="utf-8")
        saved.append(md_path)

        # 2. LaTeX
        tex_lines = [
            "% Auto-generated by src.reporting.tables",
            "\\begin{table}[htbp]",
            "\\centering",
            f"\\caption{{Experiment E2 Hybrid Ablation and Paired Significance: {ds_title}}}",
            f"\\label{{tab:e2_ablation_{ds}}}",
            "\\begin{tabular}{lrrrr}",
            "\\toprule",
            "\\multicolumn{5}{c}{\\textbf{Panel A: Ablation Variants}} \\\\",
            "\\midrule",
            "Variant & RMSE $\\downarrow$ & MAE $\\downarrow$ & NDCG@10 $\\uparrow$ & P@10 $\\uparrow$ \\\\",
            "\\midrule",
        ]
        for _, row in main_df.iterrows():
            v = row["description"]
            r_rmse = _format_cell(row["RMSE"], row["RMSE"] == best_rmse, 3, latex=True)
            r_mae = _format_cell(row["MAE"], row["MAE"] == best_mae, 3, latex=True)
            r_ndcg = _format_cell(row["NDCG@10"], row["NDCG@10"] == best_ndcg, 4, latex=True)
            r_p10 = _format_cell(row["P@10"], row["P@10"] == best_p10, 4, latex=True)
            tex_lines.append(f"{v} & {r_rmse} & {r_mae} & {r_ndcg} & {r_p10} \\\\")

        tex_lines.extend([
            "\\midrule",
            "\\multicolumn{5}{c}{\\textbf{Panel B: Paired Significance (Adaptive $-$ Fixed)}} \\\\",
            "\\midrule",
            "Metric & Mean Diff & 95\\% CI & Wilcoxon $p$ & Sig. \\\\",
            "\\midrule",
        ])
        for _, row in sig_df.iterrows():
            m = row["metric"].replace("Mean Squared Error (SE)", "Squared Error (SE)").replace("Mean Absolute Error (AE)", "Absolute Error (AE)")
            diff = f"{row['mean_difference']:.4f}"
            ci = f"[{row['ci_95_lower']:.4f}, {row['ci_95_upper']:.4f}]"
            pval = f"{row['wilcoxon_pvalue']:.2e}"
            sig = row["statistically_significant"]
            tex_lines.append(f"{m} & {diff} & {ci} & {pval} & \\textbf{{{sig}}} \\\\")

        tex_lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])

        tex_path = TABLES_DIR / f"e2_ablation_{ds}.tex"
        tex_path.write_text("\n".join(tex_lines), encoding="utf-8")
        saved.append(tex_path)

    return saved


def generate_e3_tables() -> List[Path]:
    """Generate Markdown and LaTeX tables for Experiment E3 (Activity terciles)."""
    _ensure_dir()
    saved: List[Path] = []

    for ds in ["movielens", "foodcom"]:
        csv_path = Path("results") / f"e3_{ds}.csv"
        sig_path = Path("results") / f"e3_significance_{ds}.csv"
        df = pd.read_csv(csv_path)
        sig_df = pd.read_csv(sig_path)

        ds_title = "MovieLens 100K" if ds == "movielens" else "Food.com"

        # 1. Markdown
        md_lines = [
            f"# Experiment E3: Performance by User Activity Level ({ds_title})",
            "",
            "| Activity Group | Rating Range | Model | Users | Mean alpha_u | RMSE | MAE | NDCG@10 | P@10 |",
            "| :--- | :---: | :--- | :---: | :---: | :---: | :---: | :---: | :---: |",
        ]
        for grp in ["few", "medium", "many", "all"]:
            sub = df[df["activity_group"] == grp]
            best_rmse = sub["RMSE"].min()
            best_ndcg = sub["NDCG@10"].max()
            for _, row in sub.iterrows():
                r_rmse = _format_cell(row["RMSE"], row["RMSE"] == best_rmse, 3, latex=False)
                r_mae = f"{row['MAE']:.3f}"
                r_ndcg = _format_cell(row["NDCG@10"], row["NDCG@10"] == best_ndcg, 4, latex=False)
                r_p10 = f"{row['P@10']:.4f}"
                alpha_str = f"{row['mean_adaptive_alpha']:.3f}"
                md_lines.append(
                    f"| {grp.upper()} | {row['group_rating_range']} | {row['model']} | {row['n_users']} | {alpha_str} | {r_rmse} | {r_mae} | {r_ndcg} | {r_p10} |"
                )

        md_path = TABLES_DIR / f"e3_activity_{ds}.md"
        md_path.write_text("\n".join(md_lines), encoding="utf-8")
        saved.append(md_path)

        # 2. LaTeX
        tex_lines = [
            "% Auto-generated by src.reporting.tables",
            "\\begin{table}[htbp]",
            "\\centering",
            f"\\caption{{Experiment E3 Performance by Activity Tercile: {ds_title}}}",
            f"\\label{{tab:e3_activity_{ds}}}",
            "\\begin{tabular}{llrrrr}",
            "\\toprule",
            "Group & Model & Mean $\\alpha_u$ & RMSE $\\downarrow$ & MAE $\\downarrow$ & NDCG@10 $\\uparrow$ \\\\",
            "\\midrule",
        ]
        for grp in ["few", "medium", "many"]:
            sub = df[df["activity_group"] == grp]
            best_rmse = sub["RMSE"].min()
            best_ndcg = sub["NDCG@10"].max()
            tex_lines.append(f"\\multicolumn{{6}}{{l}}{{\\textbf{{{grp.upper()} Group ({sub['group_rating_range'].iloc[0]} ratings)}}}} \\\\")
            for _, row in sub.iterrows():
                r_rmse = _format_cell(row["RMSE"], row["RMSE"] == best_rmse, 3, latex=True)
                r_mae = f"{row['MAE']:.3f}"
                r_ndcg = _format_cell(row["NDCG@10"], row["NDCG@10"] == best_ndcg, 4, latex=True)
                alpha_str = f"{row['mean_adaptive_alpha']:.3f}"
                tex_lines.append(f"& {row['model']} & {alpha_str} & {r_rmse} & {r_mae} & {r_ndcg} \\\\")
            tex_lines.append("\\midrule")
        tex_lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])

        tex_path = TABLES_DIR / f"e3_activity_{ds}.tex"
        tex_path.write_text("\n".join(tex_lines), encoding="utf-8")
        saved.append(tex_path)

    return saved


def generate_e5_tables() -> List[Path]:
    """Generate Markdown and LaTeX tables for Experiment E5 (Cross-domain comparison)."""
    _ensure_dir()
    saved: List[Path] = []

    comp_path = Path("results") / "e5_comparison.csv"
    rank_path = Path("results") / "e5_model_ranking.csv"
    if not comp_path.exists() or not rank_path.exists():
        raise FileNotFoundError("Missing E5 CSV results files.")

    df_comp = pd.read_csv(comp_path)
    df_rank = pd.read_csv(rank_path)

    best_ml_rmse = df_comp["ML_RMSE"].min()
    best_fc_rmse = df_comp["FC_RMSE"].min()
    best_ml_ndcg = df_comp["ML_NDCG@10"].max()
    best_fc_ndcg = df_comp["FC_NDCG@10"].max()

    # 1. Markdown
    md_lines = [
        "# Experiment E5: Cross-Domain Comparison (MovieLens 100K vs. Food.com)",
        "",
        "### Side-by-Side Model Performance and Relative Baseline Gains",
        "| Model | ML RMSE | ML RMSE Imp (%) | FC RMSE | FC RMSE Imp (%) | ML NDCG@10 | ML NDCG Imp (%) | FC NDCG@10 | FC NDCG Imp (%) |",
        "| :--- | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: |",
    ]
    for _, row in df_comp.iterrows():
        m = row["model"]
        ml_r = _format_cell(row["ML_RMSE"], row["ML_RMSE"] == best_ml_rmse, 3, latex=False)
        fc_r = _format_cell(row["FC_RMSE"], row["FC_RMSE"] == best_fc_rmse, 3, latex=False)
        ml_n = _format_cell(row["ML_NDCG@10"], row["ML_NDCG@10"] == best_ml_ndcg, 4, latex=False)
        fc_n = _format_cell(row["FC_NDCG@10"], row["FC_NDCG@10"] == best_fc_ndcg, 4, latex=False)

        ml_r_imp = f"{row['ML_RMSE_rel_imp_%']:+.2f}%"
        fc_r_imp = f"{row['FC_RMSE_rel_imp_%']:+.2f}%"
        ml_n_imp = f"{row['ML_NDCG_rel_imp_%']:+.2f}%"
        fc_n_imp = f"{row['FC_NDCG_rel_imp_%']:+.2f}%"

        md_lines.append(f"| {m} | {ml_r} | {ml_r_imp} | {fc_r} | {fc_r_imp} | {ml_n} | {ml_n_imp} | {fc_n} | {fc_n_imp} |")

    md_lines.extend([
        "",
        "### Model Rankings Across Domains",
        "| Model | ML Rank (RMSE) | FC Rank (RMSE) | ML Rank (NDCG@10) | FC Rank (NDCG@10) |",
        "| :--- | :---: | :---: | :---: | :---: |",
    ])
    for _, row in df_rank.iterrows():
        md_lines.append(f"| {row['model']} | {row['ML_rank_RMSE']} | {row['FC_rank_RMSE']} | {row['ML_rank_NDCG10']} | {row['FC_rank_NDCG10']} |")

    md_path = TABLES_DIR / "e5_cross_domain_comparison.md"
    md_path.write_text("\n".join(md_lines), encoding="utf-8")
    saved.append(md_path)

    # 2. LaTeX
    tex_lines = [
        "% Auto-generated by src.reporting.tables",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\caption{Cross-Domain Performance Comparison Normalized to Baselines}",
        "\\label{tab:e5_cross_domain}",
        "\\begin{tabular}{lrrrrrrrr}",
        "\\toprule",
        "& \\multicolumn{4}{c}{\\textbf{MovieLens 100K Benchmark}} & \\multicolumn{4}{c}{\\textbf{Food.com Primary Domain}} \\\\",
        "\\cmidrule(lr){2-5} \\cmidrule(lr){6-9}",
        "Model & RMSE $\\downarrow$ & $\\Delta$GM (\\%) & NDCG@10 $\\uparrow$ & $\\Delta$Pop (\\%) & RMSE $\\downarrow$ & $\\Delta$GM (\\%) & NDCG@10 $\\uparrow$ & $\\Delta$Pop (\\%) \\\\",
        "\\midrule",
    ]
    for _, row in df_comp.iterrows():
        m = row["model"]
        ml_r = _format_cell(row["ML_RMSE"], row["ML_RMSE"] == best_ml_rmse, 3, latex=True)
        fc_r = _format_cell(row["FC_RMSE"], row["FC_RMSE"] == best_fc_rmse, 3, latex=True)
        ml_n = _format_cell(row["ML_NDCG@10"], row["ML_NDCG@10"] == best_ml_ndcg, 4, latex=True)
        fc_n = _format_cell(row["FC_NDCG@10"], row["FC_NDCG@10"] == best_fc_ndcg, 4, latex=True)

        ml_r_imp = f"{row['ML_RMSE_rel_imp_%']:+.1f}\\%"
        fc_r_imp = f"{row['FC_RMSE_rel_imp_%']:+.1f}\\%"
        ml_n_imp = f"{row['ML_NDCG_rel_imp_%']:+.1f}\\%"
        fc_n_imp = f"{row['FC_NDCG_rel_imp_%']:+.1f}\\%"

        tex_lines.append(f"{m} & {ml_r} & {ml_r_imp} & {ml_n} & {ml_n_imp} & {fc_r} & {fc_r_imp} & {fc_n} & {fc_n_imp} \\\\")

    tex_lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])

    tex_path = TABLES_DIR / "e5_cross_domain_comparison.tex"
    tex_path.write_text("\n".join(tex_lines), encoding="utf-8")
    saved.append(tex_path)

    return saved


def generate_all_tables() -> List[Path]:
    """Generate all markdown and latex tables."""
    print("Generating Experiment Tables (results/tables/)...")
    saved = []
    saved.extend(generate_e1_tables())
    saved.extend(generate_e2_tables())
    saved.extend(generate_e3_tables())
    saved.extend(generate_e5_tables())
    for p in saved:
        print(f"  Saved table: {p}")
    return saved


if __name__ == "__main__":
    generate_all_tables()

